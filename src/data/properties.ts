export function getPropertyById(id: string): Property | undefined {
  return properties.find(p => p.id === id);
}

export function getFeaturedProperties(purpose?: 'sale' | 'rent'): Property[] {
  return properties.filter(p => p.isFeatured && (!purpose || p.purpose === purpose));
}

export function getSuperFeaturedProperty(): Property | undefined {
  return properties.find(p => p.isSuperFeatured);
}

export function filterProperties(filters: Partial<{
  purpose: string;
  type: string;
  neighborhood: string;
  bedrooms: string;
  priceMin: string;
  priceMax: string;
  code: string;
  sortBy: string;
}>): Property[] {
  let result = [...properties];

  if (filters.purpose) result = result.filter(p => p.purpose === filters.purpose);
  if (filters.type) result = result.filter(p => p.type === filters.type);
  if (filters.neighborhood) result = result.filter(p => p.neighborhood === filters.neighborhood);
  if (filters.bedrooms) {
    const beds = parseInt(filters.bedrooms);
    if (beds >= 4) result = result.filter(p => p.bedrooms >= 4);
    else result = result.filter(p => p.bedrooms === beds);
  }
  if (filters.priceMin) result = result.filter(p => p.price >= parseInt(filters.priceMin));
  if (filters.priceMax) result = result.filter(p => p.price <= parseInt(filters.priceMax));
  if (filters.code) result = result.filter(p => p.code.toLowerCase().includes(filters.code.toLowerCase()));

  if (filters.sortBy === 'price-asc') result.sort((a, b) => a.price - b.price);
  else if (filters.sortBy === 'price-desc') result.sort((a, b) => b.price - a.price);
  else result.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());

  return result;
}

export function formatPrice(price: number, purpose: 'sale' | 'rent'): string {
  const formatted = price.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' });
  return purpose === 'rent' ? `${formatted}/mês` : formatted;
}
